function seededRandom(seed) {
  let state = 2166136261;
  for (const char of String(seed))
    state = Math.imul(state ^ char.charCodeAt(0), 16777619) >>> 0;
  return () => {
    state = (Math.imul(1664525, state) + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

export function generateComments(idea, outcome = "steady", seed = 1) {
  const name = String(idea?.title || "this product");
  const category = THEME_COMMENTS[idea?.category]
    ? idea.category
    : classifyTheme(`${name} ${idea?.description || ""}`);
  const verdict = OUTCOME_COMMENTS[outcome] ? outcome : "steady";
  const random = seededRandom(`${seed}:${idea?.id || name}:${verdict}`);
  const take = (pool) => pool.splice(Math.floor(random() * pool.length), 1)[0];
  const themePool = [...THEME_COMMENTS[category]];
  const specific = SPECIFIC_COMMENTS.filter(({ pattern }) =>
    pattern.test(`${name} ${idea?.description || ""}`),
  ).flatMap(({ lines }) => lines);
  const text = [
    take(themePool),
    take([...NAME_COMMENTS])(name),
    take([...OUTCOME_COMMENTS[verdict]]),
    specific.length ? take(specific) : take(themePool),
    take(themePool),
  ];
  const handles = [...HANDLES];
  return text.map((message, index) => ({
    id: `${idea?.id || "discussion"}-${String(seed)}-${index}`,
    handle: take(handles),
    text: message,
    likes: Math.floor(
      random() * (verdict === "hit" ? 120 : verdict === "flop" ? 85 : 35),
    ),
  }));
}
